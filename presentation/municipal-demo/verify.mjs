import { chromium } from '../../frontend/node_modules/@playwright/test/index.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1440,height:810}});
const deckUrl = new URL('../plexus-deck.html', import.meta.url).href;
const errors = [];
const requests = [];
page.on('pageerror', error => { errors.push(error.message); console.error(error.message); });
page.on('request', request => { if (request.url().includes('/api/')) requests.push(request.url()); });
await mkdir(new URL('./shots/', import.meta.url), {recursive:true});
const checks=[];
for (const slide of ['1','2','3','4','5','6','6.1','6.2','7','8','8.1','9']) {
  await page.goto(`${deckUrl}?static#${slide}`);
  await page.reload();
  await page.waitForSelector('html[data-ready="true"]');
  await page.evaluate(() => document.fonts.ready);
  await page.evaluate(() => document.getAnimations().forEach(a=>a.finish()));
  await page.screenshot({path:new URL(`./shots/${slide}.png`,import.meta.url).pathname});
  const layout=await page.evaluate(()=>[...document.querySelectorAll('.municipal-demo h2,.municipal-metrics,.municipal-detail,.municipal-chat')].map(e=>({name:e.className,width:e.clientWidth,scroll:e.scrollWidth,bottom:e.getBoundingClientRect().bottom})));
  checks.push({slide,layout});
}
await page.goto(`${deckUrl}#2`);
await page.reload();
  await page.waitForSelector('html[data-ready="true"]');
await page.keyboard.press('ArrowRight');
await page.waitForFunction(()=>location.hash==='#3');
await page.keyboard.press('ArrowLeft');
await page.waitForFunction(()=>location.hash==='#2');
await writeFile(new URL('./validation.json',import.meta.url),JSON.stringify({errors,requests,checks},null,2));
await browser.close();
if(errors.length || requests.length) throw new Error(JSON.stringify({errors,requests}));
console.log('12 frames rendered; navigation passed; no API calls or browser errors.');
